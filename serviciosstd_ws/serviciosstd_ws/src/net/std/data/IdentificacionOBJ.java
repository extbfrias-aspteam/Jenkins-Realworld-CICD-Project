package net.std.data;

public class IdentificacionOBJ {
	private String numeroSolicitante;
	private Integer idTipoIdentificacion;
	private String valorIdentificacion;
	private String nombreTipoIdentificacion;
	private String claveTipoIdentificacion;
	public String getNumeroSolicitante() {
		return numeroSolicitante;
	}
	public void setNumeroSolicitante(String numeroSolicitante) {
		this.numeroSolicitante = numeroSolicitante;
	}
	public Integer getIdTipoIdentificacion() {
		return idTipoIdentificacion;
	}
	public void setIdTipoIdentificacion(Integer idTipoIdentificacion) {
		this.idTipoIdentificacion = idTipoIdentificacion;
	}
	public String getValorIdentificacion() {
		return valorIdentificacion;
	}
	public void setValorIdentificacion(String valorIdentificacion) {
		this.valorIdentificacion = valorIdentificacion;
	}
	public String getNombreTipoIdentificacion() {
		return nombreTipoIdentificacion;
	}
	public void setNombreTipoIdentificacion(String nombreTipoIdentificacion) {
		this.nombreTipoIdentificacion = nombreTipoIdentificacion;
	}
	public String getClaveTipoIdentificacion() {
		return claveTipoIdentificacion;
	}
	public void setClaveTipoIdentificacion(String claveTipoIdentificacion) {
		this.claveTipoIdentificacion = claveTipoIdentificacion;
	}	
}
